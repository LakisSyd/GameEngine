#include "lightclass.h"

// ─────────────────────────────────────────────────────────────────────────────
// Конструктор
// ─────────────────────────────────────────────────────────────────────────────
LightClass::LightClass()
{
    // Инициализируем свет белым цветом, направленным вдоль оси Z
    m_diffuseColor = XMFLOAT4(1.0f, 1.0f, 1.0f, 1.0f);
    m_direction = XMFLOAT3(0.0f, 0.0f, 1.0f);
}

// ─────────────────────────────────────────────────────────────────────────────
// Копирующий конструктор
// ─────────────────────────────────────────────────────────────────────────────
LightClass::LightClass(const LightClass& other)
{
    m_diffuseColor = other.m_diffuseColor;
    m_direction = other.m_direction;
}

// ─────────────────────────────────────────────────────────────────────────────
// Деструктор
// ─────────────────────────────────────────────────────────────────────────────
LightClass::~LightClass()
{
    // Освобождать нечего — класс хранит только данные
}

// ─────────────────────────────────────────────────────────────────────────────
// Установка диффузного цвета
// ─────────────────────────────────────────────────────────────────────────────
void LightClass::SetDiffuseColor(float red, float green, float blue, float alpha)
{
    m_diffuseColor = XMFLOAT4(red, green, blue, alpha);
}

// ─────────────────────────────────────────────────────────────────────────────
// Установка направления света
// ─────────────────────────────────────────────────────────────────────────────
void LightClass::SetDirection(float x, float y, float z)
{
    m_direction = XMFLOAT3(x, y, z);
}

// ─────────────────────────────────────────────────────────────────────────────
// Получение диффузного цвета
// ─────────────────────────────────────────────────────────────────────────────
XMFLOAT4 LightClass::GetDiffuseColor()
{
    return m_diffuseColor;
}

// ─────────────────────────────────────────────────────────────────────────────
// Получение направления света
// ─────────────────────────────────────────────────────────────────────────────
XMFLOAT3 LightClass::GetDirection()
{
    return m_direction;
}