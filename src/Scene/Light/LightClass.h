#pragma once
////////////////////////////////////////////////////////////////////////////////
// Имя файла: lightclass.h
////////////////////////////////////////////////////////////////////////////////
// 📌 КЛАСС: LightClass
// 💡 Назначение: Хранит параметры источника света (цвет и направление)
// 🔹 Этот класс не выполняет вычислений — только данные
////////////////////////////////////////////////////////////////////////////////

#include <DirectXMath.h>
using namespace DirectX;

class LightClass
{
public:
    // ─────────────────────────────────────────────────────────────────────────
    // Конструкторы и деструктор
    // ─────────────────────────────────────────────────────────────────────────
    LightClass();
    LightClass(const LightClass& other);
    ~LightClass();

    // ─────────────────────────────────────────────────────────────────────────
    // Методы установки параметров света
    // ─────────────────────────────────────────────────────────────────────────

    /// <summary>
    /// Устанавливает диффузный цвет света
    /// </summary>
    /// <param name="red">Красный компонент (0.0 - 1.0)</param>
    /// <param name="green">Зелёный компонент (0.0 - 1.0)</param>
    /// <param name="blue">Синий компонент (0.0 - 1.0)</param>
    /// <param name="alpha">Альфа-канал (0.0 - 1.0)</param>
    void SetDiffuseColor(float red, float green, float blue, float alpha);

    /// <summary>
    /// Устанавливает направление света (вектор)
    /// </summary>
    /// <param name="x">X компонента направления</param>
    /// <param name="y">Y компонента направления</param>
    /// <param name="z">Z компонента направления</param>
    void SetDirection(float x, float y, float z);

    // ─────────────────────────────────────────────────────────────────────────
    // Методы получения параметров света
    // ─────────────────────────────────────────────────────────────────────────

    /// <summary>
    /// Возвращает диффузный цвет света
    /// </summary>
    XMFLOAT4 GetDiffuseColor();

    /// <summary>
    /// Возвращает направление света
    /// </summary>
    XMFLOAT3 GetDirection();

private:
    // ─────────────────────────────────────────────────────────────────────────
    // Переменные-члены
    // ─────────────────────────────────────────────────────────────────────────

    XMFLOAT4 m_diffuseColor;   // Цвет света (RGBA)
    XMFLOAT3 m_direction;      // Направление света (XYZ)
};